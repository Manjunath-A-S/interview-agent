"""
evaluator.py
------------
Handles scoring individual candidate answers and synthesizing the final
interview report once all questions are complete.
"""

from typing import List, Dict, Any

import prompts
from utils import call_llm, extract_json


def evaluate_answer(
    role: str, skills: List[str], question: str, answer: str
) -> Dict[str, Any]:
    """
    Scores a single candidate answer against a question.

    Returns:
        {
            "score": int (0-10),
            "feedback": str,
            "expected_points": List[str]
        }
    """
    system_prompt, user_prompt = prompts.build_evaluation_prompt(
        role=role, skills=skills, question=question, answer=answer
    )

    raw_output = call_llm(
        system_prompt=system_prompt,
        user_prompt=user_prompt,
        temperature=0.3,
        json_mode=True,
    )

    data = extract_json(raw_output)

    # Defensively coerce/clamp the score in case the model drifts slightly
    # outside the requested schema.
    raw_score = data.get("score", 0)
    try:
        score = int(round(float(raw_score)))
    except (TypeError, ValueError):
        score = 0
    score = max(0, min(10, score))

    feedback = str(data.get("feedback", "")).strip()

    expected_points = data.get("expected_points", [])
    if not isinstance(expected_points, list):
        expected_points = [str(expected_points)]
    expected_points = [str(p).strip() for p in expected_points if str(p).strip()]

    return {
        "score": score,
        "feedback": feedback or "No feedback returned by the model.",
        "expected_points": expected_points,
    }


def generate_final_report(
    role: str, skills: List[str], qa_records: List[Dict[str, Any]]
) -> Dict[str, Any]:
    """
    Synthesizes the full interview record into a final hiring evaluation.

    overall_score / average_score are computed deterministically in Python
    (not by the LLM) so they are always numerically correct; strengths,
    weaknesses, recommendations, and the final verdict are generated by the
    LLM from the full record.
    """
    scores = [r["score"] for r in qa_records]
    overall_score = sum(scores)
    average_score = round(overall_score / len(scores), 2) if scores else 0.0

    system_prompt, user_prompt = prompts.build_final_report_prompt(
        role=role,
        skills=skills,
        qa_records=qa_records,
        overall_score=overall_score,
        average_score=average_score,
    )

    raw_output = call_llm(
        system_prompt=system_prompt,
        user_prompt=user_prompt,
        temperature=0.4,
        json_mode=True,
    )

    data = extract_json(raw_output)

    def _as_list(value):
        if isinstance(value, list):
            return [str(v).strip() for v in value if str(v).strip()]
        if value:
            return [str(value).strip()]
        return []

    return {
        "overall_score": overall_score,
        "average_score": average_score,
        "strengths": _as_list(data.get("strengths")),
        "weaknesses": _as_list(data.get("weaknesses")),
        "recommendations": _as_list(data.get("recommendations")),
        "final_verdict": str(data.get("final_verdict", "Not available")).strip(),
    }
